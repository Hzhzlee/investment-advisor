export function parseCSVToPrices(csvText: string): Array<{
  date: string;
  close: number;
  raw_close?: number;
  adj_close?: number;
  is_adjusted?: boolean;
}> {
  const lines = csvText.trim().split(/\r?\n/);
  if (lines.length < 2) return [];

  // Identify column indices from header
  const header = lines[0].toLowerCase().split(",").map(c => c.trim().replace(/^["']|["']$/g, ""));
  let dateIdx = header.findIndex(h => h.includes("date") || h.includes("time"));
  let adjCloseIdx = header.findIndex(h => h.includes("adj") || h.includes("adjusted"));
  let rawCloseIdx = header.findIndex(h => h.includes("close") && !h.includes("adj"));
  if (rawCloseIdx === -1) {
    rawCloseIdx = header.findIndex(h => h.includes("price") || h.includes("nav"));
  }

  // Fallbacks if not recognized
  if (dateIdx === -1) dateIdx = 0;
  if (rawCloseIdx === -1) rawCloseIdx = 1;

  const points: Array<{
    date: string;
    close: number;
    raw_close?: number;
    adj_close?: number;
    is_adjusted?: boolean;
  }> = [];

  for (let i = 1; i < lines.length; i++) {
    const row = lines[i].trim();
    if (!row) continue;
    const parts = row.split(",").map(p => p.trim().replace(/^["']|["']$/g, ""));
    const rawDate = parts[dateIdx];
    const rawCloseVal = parseFloat(parts[rawCloseIdx]);
    const adjCloseVal = adjCloseIdx !== -1 ? parseFloat(parts[adjCloseIdx]) : NaN;

    const hasAdj = !isNaN(adjCloseVal) && adjCloseVal > 0;
    const hasRaw = !isNaN(rawCloseVal) && rawCloseVal > 0;

    // Use adjusted close if present (for total returns), else raw close
    const finalClose = hasAdj ? adjCloseVal : (hasRaw ? rawCloseVal : NaN);

    if (rawDate && !isNaN(finalClose) && finalClose > 0) {
      // Normalise date to YYYY-MM-DD
      const parsedDate = new Date(rawDate);
      const isoDate = !isNaN(parsedDate.getTime()) 
        ? parsedDate.toISOString().slice(0, 10) 
        : rawDate.slice(0, 10);
      points.push({
        date: isoDate,
        close: Math.round(finalClose * 10000) / 10000,
        raw_close: hasRaw ? Math.round(rawCloseVal * 10000) / 10000 : undefined,
        adj_close: hasAdj ? Math.round(adjCloseVal * 10000) / 10000 : undefined,
        is_adjusted: hasAdj
      });
    }
  }

  // Sort ascending
  return points.sort((a, b) => a.date.localeCompare(b.date));
}
